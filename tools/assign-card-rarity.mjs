// Generates card-rarity.js: how often each recruitable Wa card is OFFERED.
// Rarity is a game-design parameter derived only from card rules (cost, effect
// value, build/power complexity). It never reads player names, teams or
// reputation, and it is not a grade of the real person on the card.
// Usage: node tools/assign-card-rarity.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { CARDS, REGIONS, TACTICS } from '../content.js';

const TARGET = { rare: 10, uncommon: 25 }; // per 75-card region; the rest are common
const CAPSTONE = new Set(['burnMultiply', 'detonate', 'strength', 'bodyslam', 'fireTurrets', 'power:energy', 'power:extraDraw', 'power:knife', 'power:comboAtk', 'power:burnTick']);

function value(e) {
  switch (e.type) {
    case 'hit': {
      const cond = k => (e[k] === true ? 3 : e[k] || 0) * 0.5;
      return (e.n + cond('ifWeak') + cond('ifVuln') + cond('ifBurn')) * (e.times || 1);
    }
    case 'block': return e.n * 0.8;
    case 'weak': return e.n * 2.5;
    case 'vulnerable': return e.n * 3;
    case 'draw': return e.n * 3.5;
    case 'token': return 2.5;
    case 'deploy': return e.n * e.turns * (e.kind === 'turret' ? 0.8 : 0.6);
    case 'fireTurrets': return 6;
    case 'bodyslam': return 8;
    case 'combo': return 0.6 * value(e.effect);
    case 'burn': return e.n * 1.8;
    case 'burnMultiply': case 'detonate': return 10;
    case 'strength': return e.n * 7;
    case 'overload': return -4 * e.n;
    case 'power': return { duel: 2.5, init: 1.5, knife: 4, comboAtk: 4, burnTick: 4 }[e.key] * e.n || { energy: 18, extraDraw: 14 }[e.key] || 0;
    default: return 0;
  }
}
const key = e => (e.type === 'power' ? `power:${e.key}` : e.type);

export function rarityScore(id) {
  const c = CARDS[id], list = c.effects;
  const surplus = list.reduce((sum, e) => sum + value(e), 0) - (3 + 5 * c.cost);
  const kinds = new Set(list.map(key));
  let complexity = Math.max(0, kinds.size - 1) * 1.5;
  if (c.zone === 'power') complexity += 5;
  if (TACTICS[id]?.archetype) complexity += 3;
  if ([...kinds].some(k => CAPSTONE.has(k))) complexity += 5;
  if (c.cost === 3) complexity += 3;
  if (c.zone === 'exhaust') complexity -= 1;
  if (c.zone === 'retain') complexity += 1;
  return surplus + complexity;
}

export function assign() {
  const table = {};
  for (const region of Object.values(REGIONS)) {
    const starters = new Set(region.start);
    // Starter cards stay common so the opening deck never reads as "rare".
    const ranked = region.pool.filter(id => !starters.has(id))
      .map(id => [id, rarityScore(id)])
      .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
    ranked.forEach(([id], i) => { table[id] = i < TARGET.rare ? 'rare' : i < TARGET.rare + TARGET.uncommon ? 'uncommon' : 'common'; });
    for (const id of starters) table[id] = 'common';
  }
  return table;
}

const file = new URL('../card-rarity.js', import.meta.url);
function render(table) {
  const lines = Object.keys(table).sort().map(id => `  ${id}:'${table[id]}',`);
  return `// Generated by tools/assign-card-rarity.mjs from card rules only (cost, effect value,\n// power/build complexity). Rarity = how often a card is offered as a reward or in\n// the shop. It is not a grade of the real player shown on the card.\nimport {KEYWORD_RARITY} from './wa-keyword-cards.js';\nexport const RARITY_ORDER = ['common','uncommon','rare'];\nexport const RARITY_LABELS = {common:'普通',uncommon:'罕见',rare:'稀有'};\nexport const CARD_RARITY = {\n${lines.join('\n')}\n};\n// Rules-3 keyword tactic cards carry hand-set rarities (see wa-keyword-cards.js).\nObject.assign(CARD_RARITY,KEYWORD_RARITY);\nexport function rarityOf(id){return CARD_RARITY[id]||null;}\n`;
}
if (process.argv[1]?.endsWith('assign-card-rarity.mjs')) {
  const text = render(assign());
  if (process.argv.includes('--check')) {
    const current = await readFile(file, 'utf8').catch(() => '');
    if (current !== text) { console.error('card-rarity.js is out of date'); process.exit(1); }
    console.log('card-rarity.js up to date');
  } else {
    await writeFile(file, text);
    console.log('card-rarity.js written');
  }
}
